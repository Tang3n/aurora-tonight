"""
Generate the AACGM-v2 lookup grid used by packages/model/src/aacgm.ts.

AACGM-v2 (Shepherd 2014) has no JavaScript implementation, so we precompute
magnetic latitude/longitude at 110 km (lower edge of green aurora) on a 2° grid
for two IGRF epochs and interpolate in the browser (error < 0.02° at 40–80°).

    uv venv tools/.venv && uv pip install --python tools/.venv/bin/python aacgmv2==2.7.1 numpy
    tools/.venv/bin/python tools/gen_aacgm_grid.py

Output: packages/model/src/aacgmGrid.generated.ts (do not edit by hand).
Also prints reference values used in unit tests.
"""
import base64
import datetime as dt
import pathlib

import aacgmv2
import numpy as np

ALT_KM = 110
STEP = 2
LATS = [l for l in range(-88, -28, STEP)] + [l for l in range(30, 90, STEP)]  # |lat| 30..88
LONS = list(range(0, 360, STEP))
EPOCHS = [2025, 2029]  # IGRF-14 coefficients end in 2029
MISSING = -32768

out = pathlib.Path(__file__).resolve().parent.parent / "packages" / "model" / "src" / "aacgmGrid.generated.ts"


def grid(epoch: int) -> tuple[str, str, int]:
    when = dt.datetime(epoch, 1, 1)
    la, lo = np.meshgrid(LATS, LONS, indexing="ij")
    mlat, mlon, _ = aacgmv2.convert_latlon_arr(la.ravel(), lo.ravel(), ALT_KM, when, method_code="G2A")
    missing = int(np.isnan(mlat).sum())
    to_i16 = lambda a: np.where(np.isnan(a), MISSING, np.round(a * 100)).astype("<i2")
    enc = lambda a: base64.b64encode(to_i16(a).tobytes()).decode()
    return enc(mlat), enc(mlon), missing


parts = []
for e in EPOCHS:
    mlat_b64, mlon_b64, missing = grid(e)
    print(f"epoch {e}: {len(LATS)}x{len(LONS)} cells, {missing} undefined")
    parts.append(f"  {{ year: {e}, mlat: '{mlat_b64}', mlon: '{mlon_b64}' }},")

out.write_text(
    "// GENERATED by tools/gen_aacgm_grid.py from aacgmv2 "
    f"{aacgmv2.__version__} — do not edit.\n"
    f"// AACGM-v2 at {ALT_KM} km, values ×100 as little-endian int16, {MISSING} = undefined.\n"
    f"export const AACGM_LATS = {LATS};\n"
    f"export const AACGM_LON_STEP = {STEP};\n"
    f"export const AACGM_MISSING = {MISSING};\n"
    "export const AACGM_EPOCHS = [\n" + "\n".join(parts) + "\n];\n"
)
print("wrote", out, out.stat().st_size, "bytes")

# Reference values for unit tests (exact AACGM-v2, not grid-interpolated).
when = dt.datetime(2026, 11, 18, 22, 0)
for name, lat, lon in [
    ("Stavanger", 58.97, 5.733), ("Oslo", 59.91, 10.75), ("Trondheim", 63.43, 10.39),
    ("Tromso", 69.65, 18.96), ("Prague", 50.08, 14.43), ("Fairbanks", 64.84, -147.72),
    ("Hobart", -42.88, 147.33),
]:
    mlat, mlon, _ = aacgmv2.convert_latlon(lat, lon, ALT_KM, when, method_code="G2A")
    mlt = aacgmv2.convert_mlt(mlon, when)
    print(f"REF {name}: mlat {mlat:.3f} mlon {mlon:.3f} mlt@2026-11-18T22:00Z {float(np.squeeze(mlt)):.3f}")
